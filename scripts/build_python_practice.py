def console(doc: int, number: int, *, opening: str = "", prompts: tuple[str, ...] = (),
            repeat: bool = False, result_prefix: str = "",
            answer: Callable[[str, str], str] | None = None,
            edits: tuple[tuple[str, str], ...] = (), instructions: str = "",
            result_description: str | None = None) -> None:
    """Restore the source dialogue; expected answers stay independent of reference execution."""
    task_key = key(doc, number)
    exercise = EXERCISES[task_key]
    code = SOLUTIONS[task_key]
    for original, replacement in edits:
        assert code.count(original) == 1, (doc, number, original)
        code = code.replace(original, replacement)
    if prompts:
        pieces = code.split("input()")
        assert len(pieces) == len(prompts) + 1, (doc, number, prompts)
        code = pieces[0] + "".join(
            ("input(" + repr(prompt + "\n") + ")" if prompt else "input()") + rest
            for prompt, rest in zip(prompts, pieces[1:], strict=True))
    if opening:
        code = f"print({opening!r})\n" + code
    SOLUTIONS[task_key] = code
    prompt_texts = [p for p in prompts if p]
    if not instructions:
        if opening:
            instructions = f"Перед вводом выведи «{opening}»."
        elif repeat:
            instructions = f"Перед каждым вводом, включая последний, выведи «{prompt_texts[0]}»."
        elif len(prompt_texts) == 1:
            instructions = f"Перед вводом выведи «{prompt_texts[0]}»."
        elif prompt_texts:
            instructions = "Перед вводом соответствующих данных выведи приглашения: " + \
                ", затем ".join(f"«{p}»" for p in prompt_texts) + "."
    exercise["statement"] += (" " + instructions) if instructions else ""
    PROMPT_INSTRUCTIONS[task_key] = instructions
    if result_description:
        exercise["output_description"] = result_description
    elif result_prefix:
        if result_prefix.endswith("\n"):
            exercise["output_description"] = (
                f"Строка «{result_prefix.rstrip()}», затем результат. " + exercise["output_description"])
        elif exercise["output_description"] == ONE_NUMBER:
            exercise["output_description"] = f"Строка «{result_prefix}<число>»."
        elif exercise["output_description"] == LIST_OUTPUT:
            exercise["output_description"] = (
                f"Список с подписью «{result_prefix.rstrip()}» и пробелом после неё. "
                "Элементы в квадратных скобках, через запятую и пробел.")
    if opening or prompt_texts:
        exercise["output_description"] = (
            "Приглашения к вводу, каждое на отдельной строке. " + exercise["output_description"])
    for test in exercise["tests"]:
        repetitions = len(test["input"].splitlines()) if repeat else 1
        lead = (lines(opening) if opening else "") + lines(*(prompt_texts * repetitions))
        original = test["expected_output"]
        test["expected_output"] = lead + result_prefix + (
            answer(test["input"], original) if answer else original)


