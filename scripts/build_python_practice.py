def statement_blocks(exercise: dict) -> list[dict]:
    blocks = [{"type": "text", "data": {"text": exercise["statement"]}}]
    for index, test in enumerate((t for t in exercise["tests"] if not t["is_hidden"]), 1):
        blocks.extend([
            {"type": "text", "data": {"text": f"### Пример работы {index}"}},
            {"type": "console", "data": {"lines": test["console_lines"]}},
        ])
    return blocks


def example_session(solution: str, test: dict) -> dict:
    """Record input/output events as they happen, even when their texts are identical."""
    harness = """
import contextlib
import io
import json
import sys

payload = json.load(sys.stdin)
stdin = io.StringIO(payload["input"])
transcript = io.StringIO()
events = []

def record(kind, text):
    if not text:
        return
    if events and events[-1]["type"] == kind:
        events[-1]["text"] += text
    else:
        events.append({"type": kind, "text": text})

class ConsoleOutput(io.StringIO):
    def write(self, text):
        transcript.write(text)
        record("output", text)
        return super().write(text)

stdout = ConsoleOutput()

def user_input(prompt=""):
    stdout.write(str(prompt))
    line = stdin.readline()
    if not line:
        raise EOFError("Example requested more input than provided")
    value = line.removesuffix("\\n").removesuffix("\\r")
    transcript.write(value + "\\n")
    record("input", value + "\\n")
    return value

with contextlib.redirect_stdout(stdout):
    exec(payload["source"], {"__name__": "__main__", "input": user_input})
console_lines = [{"type": event["type"], "text": line}
                 for event in events for line in event["text"].splitlines()]
print(json.dumps({"transcript": transcript.getvalue(), "console_lines": console_lines,
                  "output": stdout.getvalue(),
                  "unread_input": stdin.read()}, ensure_ascii=False))
"""
    process = subprocess.run(
        [sys.executable, "-I", "-X", "utf8", "-c", harness],
        input=json.dumps({"source": solution, "input": test["input"]}),
        capture_output=True, text=True, encoding="utf-8", timeout=3, check=True,
    )
    result = json.loads(process.stdout)
    assert result["output"].strip() == test["expected_output"].strip(), "Example differs from its test"
    assert not result["unread_input"], "Example leaves unread input"
    return {field: result[field] for field in ("transcript", "console_lines")}


def add(doc: int, number: int, title: str, statement: str, input_text: str,
        output_text: str, solution: str, cases: list[tuple[str, str]], *,
        hint: str | None = None, notes: str | None = None,
        example_count: int = 1) -> None:
    task_key = key(doc, number)
    assert task_key not in COVERAGE
    assert cases and len({i for i, _ in cases}) == len(cases)
    tests = []
    for index, (stdin, stdout) in enumerate(cases):
        category = ("example" if index < example_count else
                    "boundary" if index % 3 == 1 else
                    "unusual" if index % 3 == 2 else "normal")
        tests.append({"input": stdin, "expected_output": stdout,
                      "is_hidden": index >= example_count, "category": category,
                      "order": index})
    content = {"version": 1, "layout": "vertical", "blocks": [
        {"type": "text", "data": {"text": ""}}]}
    if hint:
        content["blocks"].append({"type": "callout", "data": {
            "variant": "tip", "title": "Подсказка", "content": hint}})
    EXERCISES[task_key] = {
        "kind": "task", "source_key": task_key, "source_number": number, "title": title,
        "statement": statement, "input_description": input_text,
        "output_description": output_text, "content": content,
        "task": {"checking_mode": "local", "starter_code": "# Напишите решение здесь.\n",
                 "time_limit_ms": 1000, "memory_limit_mb": 128},
        "tests": tests,
    }
    SOLUTIONS[task_key] = dedent(solution).strip() + "\n"
    COVERAGE[task_key] = {"source_key": task_key, "status": "imported",
                          "target_key": task_key, "notes": notes}


def defer(doc: int, number: int, reason: str, proposal: str) -> None:
    task_key = key(doc, number)
    COVERAGE[task_key] = {"source_key": task_key, "status": "deferred",
                          "target_key": None, "reason": reason, "proposal": proposal}


def duplicate(doc: int, number: int, target_doc: int, target_number: int) -> None:
    task_key = key(doc, number)
    COVERAGE[task_key] = {"source_key": task_key, "status": "duplicate",
                          "target_key": key(target_doc, target_number),
                          "reason": "Совпадает смысл и число входных элементов."}


