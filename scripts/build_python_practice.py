def count_words(doc: int, number: int, title: str, count: int, first: str,
                second: str, cases: list[tuple[str, str]]) -> None:
    add(doc, number, title,
        f"Среди {count} введённых слов подсчитайте слова «{first}» и «{second}». Регистр важен.",
        f"{count} непустых слов, каждое на отдельной строке.",
        ONE_NUMBER,
        f'count = 0\nfor i in range({count}):\n    word = input()\n'
        f'    if word == "{first}" or word == "{second}":\n        count += 1\nprint(count)', cases)


