def key(doc: int, number: int) -> str:
    source = DOCS[doc - 1]
    assert number in {t["number"] for t in source["tasks"]}
    return f"gdrive:{source['id']}:task:{number}"


def lines(*values: object) -> str:
    return "".join(f"{v}\n" for v in values)


def numbers(text: str) -> str:
    return lines(*text.split())


def pairs(rows: list[tuple[str, str]]) -> list[tuple[str, str]]:
    """Readable authoring notation for fixed integer input sequences."""
    return [(numbers(i), o) for i, o in rows]


def integer_input(count: int) -> str:
    return f"{count} целых чисел, каждое на отдельной строке."


