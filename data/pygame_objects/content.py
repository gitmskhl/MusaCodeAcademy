def program(initial, body, handler='', background=(0, 0, 0)):
    """Собирает полную учебную программу; отступы видны в экспорте."""
    return ('import pygame\nfrom random import randint\n\npygame.init()\n'
            'screen = pygame.display.set_mode((800, 600))\nclock = pygame.time.Clock()\n'
            + dedent(initial).strip() + '\n\nwhile True:\n'
            '    events = pygame.event.get()\n    for event in events:\n'
            '        if event.type == pygame.QUIT:\n            exit()\n'
            + (indent(dedent(handler).strip(), '        ') + '\n' if handler else '')
            + f'    screen.fill({background!r})\n'
            + indent(dedent(body).strip(), '    ')
            + '\n    pygame.display.update()\n    clock.tick(60)\n')


