def program(initial='', update='', center='x, 300', clear=True):
    return ('import pygame\n\npygame.init()\nscreen = pygame.display.set_mode((800, 600))\n\n'
            + (initial + '\n\n' if initial else '')
            + 'while True:\n'
            + '    for event in pygame.event.get():\n        if event.type == pygame.QUIT:\n            exit()\n\n'
            + (indent(update, '    ') + '\n\n' if update else '')
            + ('    screen.fill((0, 0, 0))\n' if clear else '')
            + f'    pygame.draw.circle(screen, (0, 255, 0), ({center}), 20)\n'
            + '    pygame.display.update()\n')


