MAPPING = []


def lesson(title, description, *steps):
    return dict(title=title, description=description, steps=list(steps))


def task(number, title, goal, requirements, hint, check, version, video=None, assets=None):
    source = SOURCES[version]
    heading = f'Задание {number}. {title}'
    MAPPING.append(dict(version=version, source=source['url'], task=heading))
    blocks = [text(goal), text('### Требования\n\n' + requirements),
              text('### Проверь себя\n\n' + check)]
    if video:
        blocks.append(text(f'[Видеопример из исходного материала]({video}). Размеры и числовые параметры бери из требований выше.'))
    if assets:
        blocks.append(text(f'[Картинки для игры]({assets}). Можно начать с геометрических фигур и затем заменить их картинками: поведение должно остаться тем же.'))
    blocks.extend([text('### Подсказка\n\n' + hint),
                   note('Как выполнять', 'Работай в локальном редакторе с Pygame. Сохрани отдельный файл main.py для этого задания и проверь игру по списку выше. Автоматической проверки графического окна здесь нет.'),
                   text(f'Основа задания: [{source["title"]}]({source["url"]}).')])
    return step(heading, *blocks)


