def program(initial='', handler='', drawing='screen.fill((0, 0, 0))'):
    return ('import pygame\n\npygame.init()\nscreen = pygame.display.set_mode((800, 600))\n\n'
            + (initial + '\n\n' if initial else '')
            + 'while True:\n'
            + '    events = pygame.event.get()\n'
            + '    for event in events:\n'
            + '        if event.type == pygame.QUIT:\n            exit()\n'
            + (indent(handler, '        ') + '\n' if handler else '')
            + '\n' + indent(drawing, '    ') + '\n'
            + '    pygame.display.update()\n')


