from textwrap import dedent


def text(value):
    return {"type": "text", "data": {"text": dedent(value).strip()}}


def code(value):
    return {"type": "code", "data": {"language": "python", "code": dedent(value).strip() + "\n"}}


def note(title, value):
    return {"type": "callout", "data": {"variant": "info", "title": title, "content": value}}


def step(title, *blocks):
    return {"title": title, "content": {"version": 1, "layout": "vertical", "blocks": list(blocks)}}


