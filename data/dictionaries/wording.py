def system_wording(title, initial, commands, *, advanced=False):
    variable = 'journal' if advanced else 'grades'
    model = 'Имя — ключ, список оценок — значение.' if advanced else 'Имя — ключ, одна оценка — значение.'
    actions = LIST_ACTIONS if advanced else SCALAR_ACTIONS
    parts = [SYSTEM_GOALS[title],
             f'Создай начальный журнал до цикла. {model}\n\n```python\n{variable} = {initial!r}\n```',
             'Перед каждой командой выводи `Введите команду`. Обрабатывай команды так:',
             '\n\n'.join(f'- `{command}` — {actions[command]}' for command in commands)
             + '\n\n- `стоп` — закончи ввод и выведи `Журнал: <весь словарь>`.']
    rules = []
    if advanced or set(commands) != {'оценка'}:
        rules.append('Все изменения сохраняй между командами. При отказе данные остаются прежними.')
    rules.append('Имена непустые и сравниваются точно.')
    if (advanced and 'оценка' in commands) or (not advanced and set(commands) & {'записать', 'добавить'}):
        rules.append('Вводимые оценки — целые числа от 2 до 5.')
    rules.append('Других команд не будет; `стоп` обязательно встретится.')
    parts.append(' '.join(rules))
    if set(commands) & {'журнал', 'итоги', 'отчет'}:
        parts.append(f'Для отчётов перебирай словарь обычным `for name in {variable}`, значения получай по имени. Суммы считай циклами. Порядок записей сохраняй.')
    return '\n\n'.join(parts)
