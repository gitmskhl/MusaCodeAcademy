def dialogue(transcript):
    inputs, outputs = [], []
    for line in dedent(transcript).strip('\n').splitlines():
        if line.startswith('>'):
            inputs.append(line[1:])
        else:
            outputs.append(line)
    return dict(input='\n'.join(inputs)+'\n', expected_output='\n'.join(outputs)+'\n')


