"""Материалы раздела «Словари»: теория, задачи и авторские проверочные ответы."""
from textwrap import dedent

LESSONS = []


def lesson(title, description):
    result = dict(title=title, description=description, steps=[])
    LESSONS.append(result)
    return result


def theory(group, title, text, code='', output='', stdin=''):
    group['steps'].append(dict(kind='theory', title=title, text=dedent(text).strip(),
                              code=dedent(code).strip(), output=output, stdin=stdin))


def task(group, title, text, fields, body, cases, starter=None):
    """Ожидаемые ответы задаются автором отдельно от эталонного кода."""
    prefix = ''
    instructions = []
    for name, prompt, kind in fields:
        prefix += f'print({prompt!r})\n{name} = ' + ('int(input())' if kind == 'int' else 'input()') + '\n'
        instructions.append(f'Выведи **{prompt}** и получи ' + ('целое число' if kind == 'int' else 'строку') + f' **{name}**.')
    tests = []
    for values, expected in cases:
        assert len(values) == len(fields)
        prompts = ''.join(prompt+'\n' for _, prompt, _ in fields)
        tests.append(dict(input=''.join(str(v)+'\n' for v in values), expected_output=prompts+expected+'\n'))
    group['steps'].append(dict(kind='task', title=title, text=text,
        instructions='\n\n'.join(instructions), reference=prefix+dedent(body).strip()+'\n',
        starter_code=starter or '# Напиши программу здесь\n', tests=tests))


def dialogue(group, title, text, code, transcripts, starter=None):
    """В расшифровке > означает ввод; остальные строки — вывод программы."""
    tests = []
    for transcript in transcripts:
        inputs, outputs = [], []
        for line in dedent(transcript).strip('\n').split('\n'):
            (inputs if line.startswith('>') else outputs).append(line[1:] if line.startswith('>') else line)
        tests.append(dict(input='\n'.join(inputs)+'\n', expected_output='\n'.join(outputs)+'\n'))
    group['steps'].append(dict(kind='task', title=title, text=text, instructions='',
        reference=dedent(code).strip()+'\n', starter_code=starter or '# Напиши программу здесь\n', tests=tests))


