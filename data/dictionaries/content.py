def system_task(group, title, initial, commands, scenarios, *, advanced=False):
    branches = LIST_BRANCHES if advanced else SCALAR_BRANCHES
    variable = 'journal' if advanced else 'grades'
    code = f'{variable} = {initial!r}\nwhile True:\n    print("Введите команду")\n    command = input()\n    if command == "стоп":\n        break\n'
    descriptions = []
    for command in commands:
        prompt_text, description, body = branches[command]
        code += f'    if command == {command!r}:\n'
        code += '\n'.join('        '+line if line else '' for line in dedent(body).strip().splitlines())+'\n'
        prompts = prompt_text.split('|') if prompt_text else []
        descriptions.append(f'- **{command}**. {description}' + (' Приглашения по порядку: '+', '.join(f'**{p}**' for p in prompts)+'.' if prompts else ''))
    code += f'print("Журнал:", {variable})\n'
    tests = []
    for events, final in scenarios:
        inputs, outputs = [], []
        for command, arguments, response in events:
            inputs.append(command)
            outputs.append('Введите команду')
            prompts = branches[command][0].split('|') if branches[command][0] else []
            assert len(prompts) == len(arguments), command
            for prompt, value in zip(prompts, arguments):
                outputs.append(prompt)
                inputs.append(str(value))
            if response:
                outputs.extend(response.split('\n'))
        inputs.append('стоп')
        outputs += ['Введите команду', 'Журнал: '+repr(final)]
        tests.append(dict(input='\n'.join(inputs)+'\n', expected_output='\n'.join(outputs)+'\n'))
    text = f'Начальное состояние: **{variable} = {initial!r}**. Создай его до цикла.\n\nПеред каждой командой выводи **Введите команду**. Поддержи команды:\n\n'+'\n'.join(descriptions)+f'\n- **стоп**. Заверши цикл и выведи **Журнал: <словарь>**.\n\nДругих команд нет. Команда **стоп** обязательно встретится. Имена непустые, оценки целые от 2 до 5. Сохраняй изменения между командами и порядок добавления ключей. При неудачной операции данные не меняются. Перебирай словарь только через **for key in dictionary**, значения получай по ключу.'
    group['steps'].append(dict(kind='task',title=title,text=text,instructions='',reference=code,starter_code='# Создай словарь, затем напиши цикл команд\n',tests=tests))

