LESSONS = []


def text(value):
    return {'type': 'text', 'data': {'text': dedent(value).strip()}}


def callout(variant, title, value):
    return {'type': 'callout', 'data': {'variant': variant, 'title': title, 'content': value}}


def code(value, output):
    return {'code': dedent(value).strip() + '\n', 'output': output}


def lesson(title, description, explanation, examples, walkthrough, warning, question):
    item = dict(title=title, description=description, steps=[dict(
        kind='theory', title='Как работает алгоритм', explanation=dedent(explanation).strip(),
        examples=examples, walkthrough=dedent(walkthrough).strip(), warning=warning, question=question)])
    LESSONS.append(item)
    return item


def task(group, title, instructions, reference, cases, source=None, prefix=''):
    """cases: вход и независимо рассчитанная часть ожидаемого вывода."""
    statement = '\n\n'.join(f'{i}. {s}' for i, s in enumerate(instructions, 1))
    group['steps'].append(dict(kind='task', title=title, statement=statement,
        reference=dedent(reference).strip()+'\n', source=source,
        tests=[dict(input=stdin, expected_output=prefix+expected+'\n') for stdin, expected in cases]))


